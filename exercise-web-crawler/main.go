package main

import (
	"fmt"
	"sync"
)

type Fetcher interface {
	// Fetch returns the body of URL and
	// a slice of URLs found on that page.
	Fetch(url string) (body string, urls []string, err error)
}

type visitedSet struct {
	mu   sync.Mutex
	seen map[string]bool
}

func (s *visitedSet) tryVisit(url string) bool {
	s.mu.Lock()
	defer s.mu.Unlock()

	if s.seen[url] {
		return false
	}
	s.seen[url] = true
	return true
}

type crawler struct {
	fetcher Fetcher
	visited visitedSet
	wg      sync.WaitGroup
}

func (c *crawler) crawl(url string, depth int) {
	defer c.wg.Done()
	if depth <= 0 || !c.visited.tryVisit(url) {
		return
	}
	body, urls, err := c.fetcher.Fetch(url)
	if err != nil {
		fmt.Println(err)
		return
	}
	fmt.Printf("found: %s %q\n", url, body)
	for _, u := range urls {
		c.wg.Add(1)
		go c.crawl(u, depth-1)
	}
}

// Crawl uses fetcher to recursively crawl
// pages starting with url, to a maximum of depth.
func Crawl(url string, depth int, fetcher Fetcher) {
	c := &crawler{fetcher: fetcher, visited: visitedSet{seen: make(map[string]bool)}}
	c.wg.Add(1)
	go c.crawl(url, depth)
	c.wg.Wait()
}

func main() {
	Crawl("https://golang.org/", 4, fetcher)
}

// fakeFetcher is Fetcher that returns canned results.
type fakeFetcher map[string]*fakeResult

type fakeResult struct {
	body string
	urls []string
}

func (f fakeFetcher) Fetch(url string) (string, []string, error) {
	if res, ok := f[url]; ok {
		return res.body, res.urls, nil
	}
	return "", nil, fmt.Errorf("not found: %s", url)
}

